"""Regenerate ``sprintwarden/ui/static/icons.js`` from a Lucide release.

The dashboard has no build step and loads nothing from the network, so the few
Lucide icons it uses are vendored as plain data (element name + attributes),
which app.js turns into inline SVG with ``createElementNS``.

    mkdir /tmp/lucide && cd /tmp/lucide && npm pack lucide-static@1.48.0
    tar -xzf lucide-static-1.48.0.tgz
    python docs/vendor_lucide.py /tmp/lucide/package

To add an icon, add its name to ICONS below and run the script again.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ICONS = [
    # app shell
    "shield-check",
    "layout-grid",
    "square-kanban",
    "arrow-left",
    "x",
    "sun",
    "moon",
    "sun-moon",
    # board columns: one circle family
    "circle-dashed",
    "circle-dot",
    "circle-check",
    "circle-pause",
    # status marks (every ✓/✗-style mark in the UI is one of these)
    "check",
    "minus",
    "diamond",
    "clock",
    "octagon-alert",
    "triangle-alert",
    # metadata
    "git-branch",
    "git-commit-horizontal",
    "layers",
    "workflow",
    "flask-conical",
    "target",
    "calendar",
    "calendar-check",
    "bot",
    "user",
    "timer",
    "zap",
    "list-checks",
    "ban",
    "message-square-text",
    "arrow-right",
    "external-link",
    "file-text",
    "grid-3x3",
    "chart-line",
    "logs",
    "skip-forward",
    "square-terminal",
    "shield",
    # board density switch
    "layout-list",
    "rows-3",
    # trends
    "trending-up",
    "trending-down",
    "move-right",
    "lightbulb",
    "book-open",
    "table",
]

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "sprintwarden" / "ui" / "static" / "icons.js"
LICENSE_OUT = REPO / "sprintwarden" / "ui" / "LICENSE-lucide.txt"


def main(package: Path) -> None:
    nodes = json.loads((package / "icon-nodes.json").read_text(encoding="utf-8"))
    version = json.loads((package / "package.json").read_text(encoding="utf-8"))["version"]
    missing = [name for name in ICONS if name not in nodes]
    if missing:
        sys.exit(f"not in Lucide {version}: {', '.join(missing)}")
    lines = [
        f"// Icons from Lucide {version} (lucide.dev). ISC License; some icons derive from",
        "// Feather (MIT). Full text: sprintwarden/ui/LICENSE-lucide.txt.",
        "// Generated by docs/vendor_lucide.py; edit that list, not this file.",
        '"use strict";',
        "",
        "const ICONS = {",
    ]
    for name in sorted(ICONS):
        lines.append(f"  {json.dumps(name)}: {json.dumps(nodes[name], separators=(',', ':'))},")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    LICENSE_OUT.write_text((package / "LICENSE").read_text(encoding="utf-8"), encoding="utf-8")
    print(f"wrote {len(ICONS)} icons from Lucide {version} to {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]))
